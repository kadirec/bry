<h4>1. Çerez Nedir?</h4>
<p>Çerezler (cookies), bir web sitesini ziyaret ettiğinizde tarayıcınıza kaydedilen küçük metin dosyalarıdır. Sitenin düzgün çalışmasını sağlamak, tercihlerinizi hatırlamak ve ziyaretçi davranışlarını anonim olarak ölçmek amacıyla kullanılırlar.</p>

<h4>2. Kullandığımız Çerez Türleri</h4>
<ul>
  <li><strong>Zorunlu çerezler:</strong> Oturum yönetimi, form güvenliği (CSRF) ve sitenin temel işlevleri için gereklidir. Devre dışı bırakılamaz.</li>
  <li><strong>Performans / analiz çerezleri:</strong> Google Analytics (GA4) aracılığıyla, hangi sayfaların ne kadar görüntülendiğini anonim olarak ölçer; içeriğimizi geliştirmemize yardımcı olur.</li>
  <li><strong>Pazarlama / hedefleme çerezleri:</strong> Meta (Facebook) Pixel aracılığıyla, reklam performansının ölçülmesi ve ilgi alanlarınıza uygun içerik gösterilmesi amacıyla kullanılır.</li>
  <li><strong>İşlevsellik çerezleri:</strong> Dil, görüntüleme ve form tercihlerinizin hatırlanmasını sağlar.</li>
</ul>

<h4>3. Üçüncü Taraf Çerezleri</h4>
<p>Sitemizde Google (Analytics) ve Meta (Facebook Pixel) hizmetleri ile YouTube/Spotify gibi gömülü içerik sağlayıcıların çerezleri bulunabilir. Bu çerezler ilgili sağlayıcıların kendi gizlilik politikalarına tabidir.</p>

<h4>4. Çerezlerin Kullanım Amacı</h4>
<ul>
  <li>Sitenin güvenli ve kesintisiz çalışmasını sağlamak,</li>
  <li>Ziyaretçi trafiğini ve içerik performansını ölçmek,</li>
  <li>Kullanıcı deneyimini iyileştirmek,</li>
  <li>Reklam ve tanıtım çalışmalarının etkinliğini değerlendirmek.</li>
</ul>

<h4>5. Çerezleri Nasıl Yönetebilirsiniz?</h4>
<p>Tarayıcınızın ayarlar bölümünden çerezleri silebilir, engelleyebilir veya çerez yerleştirildiğinde uyarı verilmesini sağlayabilirsiniz. Zorunlu çerezlerin engellenmesi halinde sitenin bazı bölümleri düzgün çalışmayabilir.</p>
<ul>
  <li>Google Chrome: Ayarlar → Gizlilik ve güvenlik → Çerezler ve diğer site verileri</li>
  <li>Safari: Tercihler → Gizlilik</li>
  <li>Mozilla Firefox: Ayarlar → Gizlilik ve Güvenlik</li>
  <li>Microsoft Edge: Ayarlar → Çerezler ve site izinleri</li>
</ul>

