<h4>1. Veri Sorumlusu</h4>
<p>İşbu KVKK Aydınlatma Metni ve Gizlilik Politikası, 6698 sayılı Kişisel Verilerin Korunması Kanunu ("KVKK") uyarınca, <strong>Bilinçli Ritmik Yaşam (BRY)</strong> tarafından veri sorumlusu sıfatıyla; <strong>www.bilincliritmikyasam.com</strong> üzerinden paylaştığınız kişisel verilerin işlenmesine ilişkin olarak sizleri bilgilendirmek amacıyla hazırlanmıştır.</p>

<h4>2. İşlenen Kişisel Veriler</h4>
<p>Site üzerinden tarafımızla paylaşmanız halinde aşağıdaki veriler işlenmektedir:</p>
<ul>
  <li><strong>Kimlik ve iletişim verileri:</strong> ad-soyad, e-posta adresi, telefon numarası, kurum adı,</li>
  <li><strong>Talep bilgileri:</strong> ilgilendiğiniz program, form üzerinden ilettiğiniz mesaj içeriği,</li>
  <li><strong>İşlem güvenliği verileri:</strong> IP adresi, tarayıcı bilgisi, ziyaret zamanı ve çerezler aracılığıyla toplanan kullanım verileri.</li>
</ul>

<h4>3. Kişisel Verilerin İşlenme Amacı</h4>
<ul>
  <li>Talep ettiğiniz bilgilendirme, teklif ve kayıt süreçlerinin yürütülmesi,</li>
  <li>Sizinle ön görüşme yapılması ve uygun programın belirlenmesi,</li>
  <li>Eğitim, seminer ve etkinlik süreçlerinin planlanması ve yürütülmesi,</li>
  <li>Müşteri ilişkileri yönetimi, kayıt ve arşiv faaliyetleri,</li>
  <li>Site güvenliğinin sağlanması ve hizmet kalitesinin ölçülmesi,</li>
  <li>Açık rızanız bulunması halinde tanıtım ve bilgilendirme iletilerinin gönderilmesi,</li>
  <li>Yasal yükümlülüklerin yerine getirilmesi.</li>
</ul>
<p>Verileriniz; KVKK m.5/2 (sözleşmenin kurulması veya ifası için gerekli olması, veri sorumlusunun meşru menfaati, hukuki yükümlülük) ve gerekli hallerde <strong>açık rızanız</strong> hukuki sebeplerine dayanılarak işlenir.</p>

<h4>4. Kişisel Verilerin Aktarılması</h4>
<p>Kişisel verileriniz; yalnızca yukarıdaki amaçlarla sınırlı olmak ve mevzuatın gerektirdiği ölçüde kalmak kaydıyla; barındırma (hosting), e-posta, ölçümleme ve ödeme altyapısı hizmeti aldığımız iş ortaklarımıza ve yetkili kamu kurum/kuruluşlarına aktarılabilir. Verileriniz <strong>ticari amaçla üçüncü kişilere satılmaz veya devredilmez</strong>.</p>

<h4>5. Toplama Yöntemi</h4>
<p>Kişisel verileriniz; web sitemizdeki iletişim ve başvuru formları, e-posta, telefon ve çerezler aracılığıyla tamamen veya kısmen otomatik yollarla elektronik ortamda toplanmaktadır.</p>

<h4>6. Saklama Süresi</h4>
<p>Kişisel verileriniz, talebinizin sonuçlandırılması ve ilgili yasal saklama süreleri boyunca muhafaza edilir; süre sonunda KVKK'nın 7. maddesine uygun olarak silinir, yok edilir veya anonim hale getirilir.</p>

<h4>7. Veri Güvenliği</h4>
<p>Kişisel verilerinizin hukuka aykırı olarak işlenmesini ve erişilmesini önlemek, muhafazasını sağlamak amacıyla uygun güvenlik düzeyini temin etmeye yönelik gerekli teknik ve idari tedbirler (SSL şifreleme, yetki kontrolü, erişim kayıtları) tarafımızca alınmaktadır.</p>

<h4>8. KVKK Madde 11 Kapsamındaki Haklarınız</h4>
<p>KVKK'nın 11. maddesi uyarınca; kişisel verilerinizin işlenip işlenmediğini öğrenme, işlenmişse buna ilişkin bilgi talep etme, işlenme amacını ve amacına uygun kullanılıp kullanılmadığını öğrenme, yurt içinde/yurt dışında aktarıldığı üçüncü kişileri bilme, eksik veya yanlış işlenmişse düzeltilmesini isteme, KVKK'nın öngördüğü şartlar çerçevesinde silinmesini veya yok edilmesini isteme, yapılan işlemlerin üçüncü kişilere bildirilmesini isteme, münhasıran otomatik sistemlerle analiz edilmesi suretiyle aleyhinize bir sonucun ortaya çıkmasına itiraz etme ve kanuna aykırı işleme nedeniyle uğradığınız zararın giderilmesini talep etme haklarına sahipsiniz.</p>

